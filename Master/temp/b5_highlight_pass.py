def find_range(words, phrase):
    toks = [norm(w) for w in phrase.split() if norm(w)]
    n = len(toks)
    nwords = [norm(w[4]) for w in words]
    for i in range(len(nwords) - n + 1):
        if nwords[i:i+n] == toks:
            return i, i + n - 1
    # fallback: tolerate words that got merged/split by joining
    joined = ""
    idx = []
    for i, w in enumerate(nwords):
        for _ in w:
            idx.append(i)
        joined += w
    target = "".join(toks)
    p = joined.find(target)
    if p >= 0:
        return idx[p], idx[p + len(target) - 1]
    return None

doc = fitz.open(SRC)
report = []
for pno, color, start, end, label in PASSAGES:
    page = doc[pno]
    words = page.get_text("words")
    words.sort(key=lambda w: (w[5], w[6], w[7]))  # block, line, word
    rs = find_range(words, start)
    re_ = find_range(words, end)
    if rs is None or re_ is None:
        report.append(f"  !! MISS p{pno+1} [{label}] start={'OK' if rs else 'MISS'} end={'OK' if re_ else 'MISS'}")
        continue
    i0, j1 = rs[0], re_[1]
    if j1 < i0:
        report.append(f"  !! ORDER p{pno+1} [{label}] end before start")
        continue
    seg = words[i0:j1+1]
    lines = {}
    for w in seg:
        key = (w[5], w[6])
        x0, y0, x1, y1 = w[0], w[1], w[2], w[3]
        if key not in lines:
            lines[key] = [x0, y0, x1, y1]
        else:
            b = lines[key]
            b[0] = min(b[0], x0); b[1] = min(b[1], y0)
            b[2] = max(b[2], x1); b[3] = max(b[3], y1)
    for b in lines.values():
        rect = fitz.Rect(b)
        a = page.add_highlight_annot(rect)
        a.set_colors(stroke=color)
        a.set_opacity(OPACITY)
        a.update()
    tag = "GREEN" if color == GREEN else "yellow"
    report.append(f"  ok  p{pno+1} {tag:6} [{label}] ({len(lines)} lines)")

doc.save(DST, garbage=4, deflate=True)
doc.close()
print(f"Saved: {DST}\n")
print("\n".join(report))
