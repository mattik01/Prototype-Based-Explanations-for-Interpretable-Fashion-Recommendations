GREEN = (0.72, 0.90, 0.70)
YELLOW = (1.00, 0.93, 0.58)
OPACITY = 0.40

LIG = {"ﬁ": "fi", "ﬂ": "fl", "ﬀ": "ff", "ﬃ": "ffi", "ﬄ": "ffl"}
def norm(s):
    for k, v in LIG.items():
        s = s.replace(k, v)
    return re.sub(r"[^a-z0-9]", "", s.lower())

# (page_index, color, start_phrase, end_phrase, label)
